// Builds the Academy quizzes from supabase/quiz-source.private.json (gitignored —
// the repo is public, so correct answers must never be committed).
//
// Outputs:
//   content/academy/quizzes.ts               questions + shuffled options, no answers (committed)
//   supabase/quiz_answer_key.private.sql     answer key to run in the Supabase SQL editor (gitignored)
//
// In the source file the FIRST option of every question is the correct one.
// Usage: node scripts/build-academy-quizzes.mjs

import { readFileSync, writeFileSync } from 'node:fs';

const source = JSON.parse(readFileSync('supabase/quiz-source.private.json', 'utf8'));

// Deterministic shuffle so re-running the script doesn't reorder options needlessly.
function seededShuffle(items, seedText) {
  let seed = 0;
  for (const ch of seedText) seed = (seed * 31 + ch.charCodeAt(0)) >>> 0;
  const rand = () => {
    seed = (seed * 1664525 + 1013904223) >>> 0;
    return seed / 2 ** 32;
  };
  const out = items.map((value, i) => ({ value, i }));
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

// All languages share one answer key, so every language gets the same option order.
// The shuffle is seeded by module + question position only.
const languages = Object.keys(source).filter((k) => !k.startsWith('_'));
const quizzes = Object.fromEntries(languages.map((lang) => [lang, {}]));
const keyRows = [];

for (const [moduleNumber, questions] of Object.entries(source.en)) {
  questions.forEach(([question], qi) => {
    const order = seededShuffle([0, 1, 2, 3], `${moduleNumber}-${qi}`).map((o) => o.value);
    keyRows.push(`('${moduleNumber}', ${qi}, ${order.indexOf(0)})`);
    for (const lang of languages) {
      const translated = source[lang][moduleNumber]?.[qi];
      if (!translated || translated[1].length !== 4) {
        throw new Error(`${lang} module ${moduleNumber} question ${qi + 1} is missing or doesn't have 4 options (${question})`);
      }
      (quizzes[lang][moduleNumber] ??= []).push({
        question: translated[0],
        options: order.map((i) => translated[1][i]),
      });
    }
  });
}

writeFileSync(
  'content/academy/quizzes.ts',
  `// GENERATED by scripts/build-academy-quizzes.mjs — edit supabase/quiz-source.private.json instead.
// Correct answers are intentionally absent; grading happens in the submit_quiz() database function.

export type QuizQuestion = { question: string; options: string[] };

export const PASS_PERCENT = 80;

export const quizzes: Record<string, Record<string, QuizQuestion[]>> = ${JSON.stringify(quizzes, null, 2)};

export function getQuiz(number: string, locale: string): QuizQuestion[] | undefined {
  return (quizzes[locale] ?? quizzes.en)[number] ?? quizzes.en[number];
}
`
);

writeFileSync(
  'supabase/quiz_answer_key.private.sql',
  `-- GENERATED by scripts/build-academy-quizzes.mjs — do not commit.
begin;
delete from public.quiz_answer_key;
insert into public.quiz_answer_key (module_number, question_index, correct_option) values
${keyRows.join(',\n')};
commit;
`
);

console.log(`Wrote ${keyRows.length} questions in ${languages.join(', ')}.`);
